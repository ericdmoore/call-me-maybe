const DefaultLibrary = "/var/spool/asterisk/cmm-books/library"
const sampleRate = 16000
const maxJSONBytes = 2 << 20

var errJSONTooLarge = errors.New("JSON exceeds the 2 MiB limit")

var idPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,63}$`)

// ValidID reports whether id is a book id a catalog may hold — what a public
// line's [[shelves]] titles must be (internal/policy keeps the same rule).
func ValidID(id string) bool { return idPattern.MatchString(id) }

var revisionPattern = regexp.MustCompile(`^[a-f0-9]{64}$`)

// Catalog order is the spoken order. Audio paths in a preparation input are
// local files, relative to that input file or absolute. Published paths are
// generated by Prepare; source paths never enter the published catalog.
type Catalog struct {
	Schema int    `json:"schema"`
	Books  []Book `json:"books"`
}

type Book struct {
	SourceHash  string    `json:"sourceHash,omitempty"`
	Feed        string    `json:"feed,omitempty"`
	Storage     string    `json:"storage,omitempty"`
	ID          string    `json:"id"`
	Title       string    `json:"title"`
	Language    string    `json:"language"`
	Origin      string    `json:"origin"`
	Preview     bool      `json:"preview,omitempty"`
	Revision    string    `json:"revision,omitempty"`
	IndexSHA256 string    `json:"indexSha256,omitempty"`
	Chapters    []Chapter `json:"chapters"`
}

type Segment struct {
	Audio   string  `json:"audio"`
	Bytes   int64   `json:"bytes"`
	SHA256  string  `json:"sha256"`
	Seconds float64 `json:"seconds"`
}

type Chapter struct {
	Segments     []Segment `json:"-"`
	SegmentCount int       `json:"segmentCount,omitempty"`
	Title        string    `json:"title"`
	Audio        string    `json:"audio"`
	Seconds      float64   `json:"seconds,omitempty"`
	Bytes        int64     `json:"bytes,omitempty"`
}

func readJSON(path string, dst any) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	d := json.NewDecoder(io.LimitReader(f, maxJSONBytes))
	d.DisallowUnknownFields()
	if err := d.Decode(dst); err != nil {
		return err
	}
	var extra any
	if d.Decode(&extra) != io.EOF {
		return errors.New("trailing or oversized JSON")
	}
	return nil
}

func writeJSON(path string, value any) error { return publishJSON(path, value, 0o600) }

func encodeJSON(value any) ([]byte, error) {
	data, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return nil, err
	}
	// Include the final newline: anything we publish must fit the same bound
	// used by the runtime reader, before touching the previous live file.
	if len(data)+1 > maxJSONBytes {
		return nil, errJSONTooLarge
	}
	return append(data, '\n'), nil
}

func publishJSON(path string, value any, mode os.FileMode) error {
	data, err := encodeJSON(value)
	if err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".publish-")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err := f.Chmod(mode); err != nil {
		_ = f.Close()
		return err
	}
	if _, err = f.Write(data); err == nil {
		err = f.Sync()
	}
	closeErr := f.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	return os.Rename(f.Name(), path)
}

func validText(s string) bool {
	return strings.TrimSpace(s) != "" && len(s) <= 240 && !strings.ContainsAny(s, "\r\n\x00")
}

func validate(c Catalog, prepared bool) error {
	if c.Schema != 1 || len(c.Books) > 128 {
		return errors.New("unsupported or oversized catalog")
	}
	seen := map[string]bool{}
	for _, b := range c.Books {
		if !idPattern.MatchString(b.ID) || seen[b.ID] || !validText(b.Title) || !idPattern.MatchString(b.Language) || len(b.Chapters) == 0 || len(b.Chapters) > 999 {
			return errors.New("invalid book identity or chapters")
		}
		seen[b.ID] = true
		if b.Origin != "cli" && b.Origin != "store" && b.Origin != "browser" && b.Origin != "podcast" {
			return errors.New("book origin must be explicit")
		}
		if b.SourceHash != "" && (b.Origin != "podcast" || !revisionPattern.MatchString(b.SourceHash)) {
			return errors.New("invalid podcast source revision")
		}
		if b.Feed != "" && (b.Origin != "podcast" || !idPattern.MatchString(b.Feed)) {
			return errors.New("invalid podcast source")
		}
		if b.Storage != "" && (!prepared || b.Storage != "opus" || b.IndexSHA256 != "") {
			return errors.New("unsupported recording storage")
		}
		if prepared && !revisionPattern.MatchString(b.Revision) {
			return errors.New("invalid recording revision")
		}
		compressed := false
		for _, ch := range b.Chapters {
			compressed = compressed || ch.SegmentCount > 0
		}
		if prepared && ((compressed && !revisionPattern.MatchString(b.IndexSHA256)) || (!compressed && b.IndexSHA256 != "")) {
			return errors.New("invalid recording index")
		}
		for i, ch := range b.Chapters {
			if !validText(ch.Title) || ch.Audio == "" || strings.ContainsAny(ch.Audio, "\r\n\x00") {
				return errors.New("invalid chapter")
			}
			audioValid := validChapterAudio(ch, i)
			if b.Storage == "opus" {
				audioValid = ch.Audio == chapterName(i)+".ffconcat" && ch.SegmentCount == 0
			}
			if b.Origin == "podcast" {
				audioValid = ch.Audio == chapterName(i)+".opus" && ch.SegmentCount == 0
			}
			if prepared && (!audioValid || ch.Seconds <= 0 || ch.Seconds > 86400) {
				return errors.New("invalid prepared chapter")
			}
		}
	}
	return nil
}

func chapterName(i int) string           { return fmt.Sprintf("chapter-%03d", i+1) }
func bookDir(root string, b Book) string { return filepath.Join(root, b.ID+"-"+b.Revision) }

// Load freezes one browse session's order. Readiness is checked again when a
// selection is made: a removed book cannot accidentally select its neighbour.
func Load(root string) (Catalog, error) {
	var c Catalog
	err := readJSON(filepath.Join(root, "catalog.json"), &c)
	if err == nil {
		err = validate(c, true)
	}
	return c, err
}

func ready(root string, b Book) bool { return artifactReady(root, b, true) }
func artifactReady(root string, b Book, live bool) bool {
	if b.Origin == "podcast" {
		paths := []string{filepath.Join(bookDir(root, b), "title.sln16")}
		for i := range b.Chapters {
			paths = append(paths, filepath.Join(bookDir(root, b), chapterName(i)+"-title.sln16"))
		}
		for name := range prompts {
			if !live {
				continue
			}
			set := "prompts-v1"
			if _, err := os.Stat(filepath.Join(root, "prompts-podcasts-v2")); err == nil {
				set = "prompts-podcasts-v2"
			}
			paths = append(paths, filepath.Join(root, set, name+".sln16"))
		}
		for _, path := range paths {
			st, err := os.Lstat(path)
			if err != nil || !st.Mode().IsRegular() || st.Size() == 0 {
				return false
			}
		}
	}
	var err error
	if live {
		c, err := Load(root)
		if err != nil {
			return false
		}
		found := false
		for _, live := range c.Books {
			if live.ID == b.ID && live.Revision == b.Revision {
				found = true
				break
			}
		}
		if !found {
			return false
		}
	}

	if b.IndexSHA256 != "" {
		b, err = hydrateRecorded(root, b)
		if err != nil {
			return false
		}
	}
	for _, ch := range b.Chapters {
		if b.Storage == "opus" {
			if !compressedChapterReady(bookDir(root, b), ch) {
				return false
			}
			continue
		}
		if len(ch.Segments) == 0 {
			st, err := os.Lstat(filepath.Join(bookDir(root, b), ch.Audio))
			if err != nil || !st.Mode().IsRegular() || !audioSizeOK(b, ch, st.Size()) {
				return false
			}
		} else {
			expected := concatChapter(ch)
			actual, err := os.ReadFile(filepath.Join(bookDir(root, b), ch.Audio))
			if err != nil || string(actual) != expected {
				return false
			}
			for _, seg := range ch.Segments {
				st, err := os.Lstat(filepath.Join(bookDir(root, b), seg.Audio))
				if err != nil || !st.Mode().IsRegular() || st.Size() != seg.Bytes {
					return false
				}
			}
		}
	}
	return true
}

// Prepare publishes the whole requested catalog only after every recording and
// prompt is ready. Immutable revision directories keep active calls valid.
// Old revisions are deliberately retained; remove them only when no call uses
// them. This is an import, never a live TTS or paid synthesis operation.
func Prepare(ctx context.Context, source, root string) error {
	return prepare(ctx, source, root, nil)
}

// PreparePodcasts retains already verified immutable episodes and publishes the
// complete next catalog once. A failed addition never replaces the live catalog.
func PreparePodcasts(ctx context.Context, source, root string, retained []Book) error {
	for _, b := range retained {
		if b.Origin != "podcast" || !artifactReady(root, b, false) {
			return errors.New("retained podcast unavailable")
		}
	}
	return prepare(ctx, source, root, retained)
}
func prepare(ctx context.Context, source, root string, retained []Book) error {
	var c Catalog
	if err := readJSON(source, &c); err != nil {
		return err
	}
	if err := validate(c, false); err != nil {
		return err
	}
	if err := preflightCatalog(c); err != nil {
		return err
	}
	if _, err := exec.LookPath("ffmpeg"); err != nil {
		return errors.New("prepare requires ffmpeg")
	}
	if _, err := exec.LookPath("espeak-ng"); err != nil {
		return errors.New("prepare requires espeak-ng for offline menu prompts")
	}
	if err := os.MkdirAll(root, 0o755); err != nil {
		return err
	}
	unlock, err := lockLibrary(root)
	if err != nil {
		return err
	}
	defer unlock()
	for i := range c.Books {
		if err := prepareEdition(ctx, source, root, &c.Books[i]); err != nil {
			return err
		}
	}
	// Version the small common prompt set independently of recording editions.
	promptSet := "prompts-v1"
	if len(c.Books) > 0 && c.Books[0].Origin == "podcast" || len(retained) > 0 {
		promptSet = "prompts-podcasts-v2"
	}
	promptRoot := filepath.Join(root, promptSet)
	if _, err := os.Stat(promptRoot); os.IsNotExist(err) {
		stage, err := os.MkdirTemp(root, ".prompts-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(stage)
		for name, words := range prompts {
			if promptSet == "prompts-podcasts-v2" {
				switch name {
				case "books":
					words = "Here are your podcast episodes."
				case "empty":
					words = "There are no podcast episodes ready. Zero to go back."
				case "book":
					words = "Two: start from the beginning. Star to repeat. Zero: back to episodes."
				}
			}
			if err := speak(ctx, filepath.Join(stage, name+".sln16"), words); err != nil {
				return err
			}
		}
		if err := os.Chmod(stage, 0o755); err != nil {
			return err
		}
		if err := os.Rename(stage, promptRoot); err != nil {
			return err
		}
	}
	c.Books = append(c.Books, retained...)
	if err := validate(c, true); err != nil {
		return err
	}
	if err := publishJSON(filepath.Join(root, "catalog.json"), c, 0o644); err != nil {
		return err
	}
	return retireStaleMenus(root)
}

// StagePodcast prepares one immutable edition without publishing a new menu.
// The worker can bound the working set and isolate episode failures before committing.
func StagePodcast(ctx context.Context, root string, b Book) (Book, error) {
	if b.Origin != "podcast" {
		return b, errors.New("not a podcast")
	}
	if err := validate(Catalog{Schema: 1, Books: []Book{b}}, false); err != nil {
		return b, err
	}
	if err := os.MkdirAll(root, 0755); err != nil {
		return b, err
	}
	unlock, err := lockLibrary(root)
	if err != nil {
		return b, err
	}
	defer unlock()
	err = prepareEdition(ctx, "", root, &b)
	return b, err
}
func prepareEdition(ctx context.Context, source, root string, b *Book) error {
	stage, err := os.MkdirTemp(root, ".prepare-")
	if err != nil {
		return err
	}
	err = prepareBook(ctx, source, stage, b)
	if err == nil {
		target := bookDir(root, *b)
		if info, statErr := os.Lstat(target); os.IsNotExist(statErr) {
			err = os.Chmod(stage, 0o755)
			if err == nil {
				err = os.Rename(stage, target)
			}
		} else if statErr != nil || !info.IsDir() {
			err = errors.New("recording revision directory unavailable")
		} else {
			// Do not publish an index pointing at a damaged old revision.
			for _, ch := range b.Chapters {
				st, e := os.Lstat(filepath.Join(target, ch.Audio))
				if e != nil || !st.Mode().IsRegular() || !audioSizeOK(*b, ch, st.Size()) {
					err = errors.New("existing recording revision is damaged")
					break
				}
			}
		}
	}
	_ = os.RemoveAll(stage)
	if err != nil {
		return err
	}
	return nil
}

// Reject catalogs that cannot fit even with the shortest duration encoding,
// before converting audio. Actual durations can occupy more bytes, so the
// final publication still checks its exact encoding. Copy the chapters to
// preserve the source paths needed by prepareBook.
func preflightCatalog(c Catalog) error {
	prepared := Catalog{Schema: c.Schema, Books: make([]Book, len(c.Books))}
	for i, b := range c.Books {
		b.Revision = strings.Repeat("0", 64)
		b.Chapters = append([]Chapter(nil), b.Chapters...)
		for j := range b.Chapters {
			b.Chapters[j].Audio = chapterName(j) + ".sln16"
			b.Chapters[j].Segments = nil
			b.Chapters[j].SegmentCount = 0
			b.IndexSHA256 = ""
			b.Chapters[j].Seconds = 1
		}
		prepared.Books[i] = b
	}
	_, err := encodeJSON(prepared)
	return err
}

func prepareBook(ctx context.Context, source, stage string, b *Book) error {
	hash := sha256.New()
	// Hash edition identity and order, not machine-specific source paths.
	fmt.Fprintf(hash, "books-pcm-v1\x00%s\x00%s\x00%s\x00%t", b.ID, b.Title, b.Language, b.Preview)
	for i := range b.Chapters {
		ch := &b.Chapters[i]
		input := ch.Audio
		if !filepath.IsAbs(input) {
			input = filepath.Join(filepath.Dir(source), input)
		}
		input, err := filepath.Abs(input)
		if err != nil {
			return err
		}
		st, err := os.Stat(input)
		if err != nil || !st.Mode().IsRegular() {
			return errors.New("chapter source must be a local regular file")
		}
		sourceSeconds := float64(0)
		if b.Origin == "podcast" {
			sourceSeconds, err = sourceDuration(ctx, input)
			if err != nil {
				return err
			}
		}
		output := filepath.Join(stage, chapterName(i)+audioSuffix(*b))
		job, cancel := context.WithTimeout(ctx, 30*time.Minute)
		args := []string{"-nostdin", "-v", "error", "-protocol_whitelist", "file,pipe", "-i", input, "-map", "0:a:0", "-vn"}
		if b.Origin == "podcast" {
			args = append(args, "-t", "7200", "-ac", "2", "-ar", "48000", "-c:a", "libopus", "-b:a", "48k", "-vbr", "on", "-fflags", "+bitexact", "-map_metadata", "-1", "-f", "opus")
		} else {
			args = append(args, "-ac", "1", "-ar", "16000", "-f", "s16le")
		}
		args = append(args, "-y", output)
		err = exec.CommandContext(job, "ffmpeg", args...).Run()
		cancel()
		if err != nil {
			return errors.New("chapter audio conversion failed")
		}
		f, err := os.Open(output)
		if err != nil {
			return err
		}
		fmt.Fprintf(hash, "\x00%s\x00", ch.Title)
		n, err := io.Copy(hash, f)
		_ = f.Close()
		if err != nil || n == 0 || (b.Origin != "podcast" && n%2 != 0) {
			return errors.New("empty or invalid chapter audio")
		}
		ch.Audio, ch.Seconds = filepath.Base(output), float64(n)/(sampleRate*2)
		if b.Origin == "podcast" {
			if n > 64<<20 {
				return errors.New("podcast artifact exceeds limit")
			}
			ch.Bytes = n
			ch.Seconds, err = verifyOpus(ctx, output)
			if err != nil {
				return err
			}
			if math.Abs(ch.Seconds-sourceSeconds) > 1 {
				return errors.New("Opus conversion changed episode duration")
			}
		}
		ch.Segments = nil
		ch.SegmentCount = 0
		b.IndexSHA256 = ""
		if ch.Seconds > 86400 {
			return errors.New("chapter exceeds one day")
		}
		if err := speak(ctx, filepath.Join(stage, chapterName(i)+"-title.sln16"), ch.Title); err != nil {
			return err
		}
	}
	b.Revision = hex.EncodeToString(hash.Sum(nil))
	title := b.Title
	if b.Preview {
		title += ". Preview recording."
	}
	return speak(ctx, filepath.Join(stage, "title.sln16"), title)
}

func speak(ctx context.Context, output, words string) error {
	job, cancel := context.WithTimeout(ctx, time.Minute)
	defer cancel()
	wav := output + ".wav"
	defer os.Remove(wav)
	cmd := exec.CommandContext(job, "espeak-ng", "-v", "en-us", "-s", "155", "-w", wav, "--stdin")
	cmd.Stdin = strings.NewReader(words)
	if cmd.Run() != nil {
		return errors.New("offline menu speech failed")
	}
	if exec.CommandContext(job, "ffmpeg", "-nostdin", "-v", "error", "-i", wav, "-ac", "1", "-ar", "16000", "-f", "s16le", "-y", output).Run() != nil {
		return errors.New("menu audio conversion failed")
	}
	return nil
}

